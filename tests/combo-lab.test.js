const assert=require('node:assert/strict');const C=require('../js/combo-lab.js');
const now=Date.parse('2026-10-21T01:00:00Z');
const m={id:'m',type:'spread',yes_ask:40,yes_bid:38,no_cost:62};
const ev=(slug,start='2026-10-21T02:00:00Z')=>({slug,start_time:start,teams:[{abbr:'a'},{abbr:'b'}],markets:[{...m}]});
assert.equal(C.eligibleEvent(ev('late'),now),true);
assert.equal(C.eligibleEvent(ev('tomorrow','2026-10-21T05:00:00Z'),now),false);
assert.equal(C.eligibleEvent({...ev('final'),finished:true},now),false);
assert.equal(C.eligibleEvent({...ev('leader'),teams:[]},now),false);
assert.equal(C.candidates({...ev('blocked'),markets:[{...m,yes_buyable:false}]}).length,0);
assert.equal(C.candidates({...ev('wide'),markets:[{...m,yes_bid:30}]}).length,0);
assert.equal(C.candidates({...ev('unknown'),markets:[{...m,yes_bid:null}]}).length,0);
assert.equal(C.candidates({...ev('bad-player'),markets:[{...m,type:'prop',player:'Player',team:'c'}]}).length,0);
assert.equal(C.candidates(ev('props'),'props').length,0);
const events=Array.from({length:6},(_,i)=>ev('g'+i));
events[1].markets=[{...m,type:'prop',player:'Player',team:'a'}];
const picks=C.choose(events,{count:4,now,random:()=>0.3});assert.equal(picks.length,4);assert.equal(new Set(picks.map(p=>p.ev.slug)).size,4);
assert.equal(C.choose([ev('g'),ev('g'),ev('b')],{count:3,now}).length,0);
assert.equal(C.choose(events,{count:6,mode:'lines',now}).length,0);
assert.equal(C.multiplier([{price:50},{price:25}]),8);
assert.throws(()=>C.choose(events,{count:12,now}));
assert.equal(m.eventSlug,undefined);
console.log('Combo generator: CT dates, final/non-games, tradability, liquidity, player attribution, unique games, exact count and price math passed');
